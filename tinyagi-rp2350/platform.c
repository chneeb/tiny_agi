// -----------------------------------------------------------------------
// Game directory set by main() after the dir chooser runs.
// -----------------------------------------------------------------------
char game_dir[64];

// -----------------------------------------------------------------------
// File I/O
// -----------------------------------------------------------------------
agi_file_t get_file(const char *filename) {
    char path[96];
    snprintf(path, sizeof(path), "%s/%s", game_dir, filename);
    size_t sz = 0;
    uint8_t *data = sd_read_file(path, &sz);
    if (!data)
        printf("SD FAIL: %s\n", path);
    agi_file_t f = { .data = data, .size = sz };
    return f;
}

void free_file(agi_file_t file) {
    sd_free_file(file.data);
}

size_t read_file_at(const char *filename, size_t offset, uint8_t *buf, size_t len) {
    char path[96];
    snprintf(path, sizeof(path), "%s/%s", game_dir, filename);
    return sd_read_file_at(path, offset, buf, len);
}

// -----------------------------------------------------------------------
// Save / restore
// -----------------------------------------------------------------------
agi_save_data_file_ptr agi_save_data_open(const char *mode) {
    char path[96];
    snprintf(path, sizeof(path), "%s/agi_save.dat", game_dir);
    bool write = (mode[0] == 'w');
    sd_save_open(path, write);
    return (agi_save_data_file_ptr)1;
}

void agi_save_data_write(agi_save_data_file_ptr file_ptr, void *data, size_t size) {
    (void)file_ptr;
    sd_save_write(data, size);
}

void agi_save_data_read(agi_save_data_file_ptr file_ptr, void *destination, size_t size) {
    (void)file_ptr;
    sd_save_read(destination, size);
}

void agi_save_data_close(agi_save_data_file_ptr file_ptr) {
    (void)file_ptr;
    sd_save_close();
}

// -----------------------------------------------------------------------
// Keyboard → AGI input queue mapping.
// Key codes follow PicoCalc conventions; KB_ENTER_CODE and KB_F10_CODE
// are set per-target in CMakeLists.txt.
// -----------------------------------------------------------------------
static void push_kbd_event(int key) {
    char ascii = 0;
    uint8_t scancode = 0;

    switch (key) {
        case 0xB5: scancode = AGI_KEY_UP;    break;
        case 0xB6: scancode = AGI_KEY_DOWN;  break;
        case 0xB4: scancode = AGI_KEY_LEFT;  break;
        case 0xB7: scancode = AGI_KEY_RIGHT; break;
        case 0xD2: scancode = AGI_KEY_HOME;  break;
        case 0xD1: scancode = AGI_KEY_INS;   break;
        case 0xD4: scancode = AGI_KEY_DEL;   break;
        case 0x81: scancode = AGI_KEY_F1;    break;
        case 0x82: scancode = AGI_KEY_F2;    break;
        case 0x83: scancode = AGI_KEY_F3;    break;
        case 0x84: scancode = AGI_KEY_F4;    break;
        case 0x85: scancode = AGI_KEY_F5;    break;
        case 0x86: scancode = AGI_KEY_F6;    break;
        case 0x87: scancode = AGI_KEY_F7;    break;
        case 0x88: scancode = AGI_KEY_F8;    break;
        case 0x89: scancode = AGI_KEY_F9;    break;
        case KB_F10_CODE: scancode = AGI_KEY_F10; break;
        case 0x08: ascii = '\b';             break;
        case 0x09: ascii = '\t';             break;
        case 0x1B: ascii = 27;              break;  // ESC / Ctrl+[
        case 0xB1: ascii = 27;              break;  // PicoCalc ESC key (harmless on RESTOUCH)
        default:
            if (key >= 0x20 && key < 0x7F)
                ascii = (char)key;
            break;
    }

    if (ascii || scancode)
        agi_input_queue_push_keypress(ascii, scancode);
}

void platform_debug_flush(void) {
    stdio_flush();
}

void check_key(void) {
    int key = kbd_read();
    if (key < 0) return;
    if (key == KB_ENTER_CODE) {
        state.enter_pressed = true;
    } else {
        push_kbd_event(key);
    }
}

// -----------------------------------------------------------------------
// Sound
// -----------------------------------------------------------------------
void platform_tick_sound(void) {
#if SOUND_ENABLED
    static uint32_t last_ms = 0;
    static uint32_t accum_ms = 0;
    static bool first_call = true;

    uint32_t now_ms = to_ms_since_boot(get_absolute_time());
    if (first_call) {
        last_ms = now_ms;
        first_call = false;
        return;
    }
    uint32_t delta = now_ms - last_ms;
    last_ms = now_ms;

    // Cap delta to avoid fast-forwarding sound after a long blocking call.
    if (delta > 150) delta = 150;

    accum_ms += delta;

    // 1 AGI sound tick = 1/60 s ≈ 16.67 ms
    int ticks = (int)(accum_ms * 60 / 1000);
    if (ticks <= 0) return;
    accum_ms -= (uint32_t)(ticks * 1000 / 60);

    if (state.sound_flag > -1 && agi_sound_is_playing()) {
        if (!agi_sound_tick(ticks)) {
            state.flags[state.sound_flag] = true;
            state.sound_flag = -1;
            agi_stop_sound();
        }
    }
#endif
}

void platform_flush_display(void) {
    flush_display();
#if SOUND_ENABLED
    platform_tick_sound();
#endif
}

void wait_for_enter(void) {
    flush_display();
    while (1) {
#if SOUND_ENABLED
        platform_tick_sound();
#endif
        int key = kbd_read();
        if (key < 0) continue;
        // KB_ENTER_CODE, PicoCalc ESC (0xB1), and standard ESC (0x1B) all dismiss.
        if (key == KB_ENTER_CODE || key == 0xB1 || key == 0x1B)
            return;
        push_kbd_event(key);
    }
}

bool wait_for_key_yn(void) {
    flush_display();
    while (1) {
        int key = kbd_read();
        if (key < 0) continue;
        if (key == 'y' || key == 'Y') return true;
        if (key == 'n' || key == 'N' || key == 0xB1 || key == 0x1B) return false;
    }
}

void agi_play_sound(uint8_t *sound_data) {
#if SOUND_ENABLED
    agi_sound_start(sound_data);
#else
    /* No audio hardware on this target.  Signal sound completion immediately
     * so game logic that waits for the sound-done flag doesn't hang.  Such a
     * wait is often a tight bytecode goto-loop that never returns to the main
     * game loop, so it must be satisfied synchronously here (a deferred
     * platform_tick_sound() would never get a chance to run).  This also frees
     * the single sound channel (sound_flag) for the next sound() call. */
    (void)sound_data;
    if (state.sound_flag > -1) {
        state.flags[state.sound_flag] = true;
        state.sound_flag = -1;
    }
#endif
}

void agi_stop_sound(void) {
#if SOUND_ENABLED
    agi_sound_stop();
#endif
}

